#!/usr/bin/env node
/**
 * One-shot Droplet setup: verify Netts/TRON env, enable in-process sweep scheduler,
 * and (with --apply) start or reload PM2 — no manual crontab.
 *
 * Usage:
 *   cd backend && node scripts/setup-droplet-sweep-automation.js
 *   cd backend && node scripts/setup-droplet-sweep-automation.js --apply
 *   cd backend && node scripts/setup-droplet-sweep-automation.js --apply --dry-run-scheduler
 */
'use strict';

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const BACKEND_DIR = path.join(__dirname, '..');
process.chdir(BACKEND_DIR);
require('../src/lib/loadEnv');

const { evaluateSweepEnv } = require('../src/services/tronSweepEnvCheck');
const {
  isVercelServerless,
  getSweepIntervalMs,
} = require('../src/services/tronSweepSchedulerService');

const PM2_APP_NAME = process.env.PM2_APP_NAME?.trim() || 'eisy-backend';
const ENV_FILE = path.join(BACKEND_DIR, '.env');

function parseArgs(argv) {
  return {
    apply: argv.includes('--apply'),
    dryRunScheduler: argv.includes('--dry-run-scheduler'),
    help: argv.includes('--help') || argv.includes('-h'),
  };
}

function upsertEnvLines(filePath, entries) {
  let text = '';
  if (fs.existsSync(filePath)) {
    text = fs.readFileSync(filePath, 'utf8');
  }
  const lines = text.length ? text.split(/\n/) : [];
  for (const [key, value] of entries) {
    const idx = lines.findIndex((line) => line.startsWith(`${key}=`));
    const row = `${key}=${value}`;
    if (idx >= 0) lines[idx] = row;
    else lines.push(row);
  }
  const out = `${lines.filter((l, i, arr) => !(i === arr.length - 1 && l === '')).join('\n')}\n`;
  fs.writeFileSync(filePath, out, { mode: 0o600 });
}

function writeEcosystemConfig() {
  const target = path.join(BACKEND_DIR, 'ecosystem.config.cjs');
  const content = `'use strict';
/** Generated by setup-droplet-sweep-automation.js — PM2 starts Express + in-process sweep scheduler. */
module.exports = {
  apps: [{
    name: ${JSON.stringify(PM2_APP_NAME)},
    script: 'server.js',
    cwd: ${JSON.stringify(BACKEND_DIR)},
    instances: 1,
    autorestart: true,
    max_memory_restart: '800M',
    env: {
      NODE_ENV: 'production',
    },
  }],
};
`;
  fs.writeFileSync(target, content, 'utf8');
  return target;
}

function runPm2(args) {
  const result = spawnSync('pm2', args, {
    cwd: BACKEND_DIR,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  });
  return result;
}

async function main() {
  const opts = parseArgs(process.argv.slice(2));
  if (opts.help) {
    console.log(`Usage:
  node scripts/setup-droplet-sweep-automation.js [--apply] [--dry-run-scheduler]

  --apply                 Write TRON_SWEEP_SCHEDULER_ENABLED=true to backend/.env,
                          write ecosystem.config.cjs, pm2 start or reload
  --dry-run-scheduler     Also set TRON_SWEEP_SCHEDULER_DRY_RUN=true (no on-chain txs)`);
    process.exit(0);
  }

  if (isVercelServerless()) {
    console.error('This setup targets a long-running Droplet host, not Vercel serverless.');
    process.exit(1);
  }

  console.log('== TRON sweep automation setup ==\n');

  const report = await evaluateSweepEnv({ verifyAddresses: false, preflightLimit: 1 });
  for (const row of report.checks.results) {
    console.log(`  ${row.ok ? '✓' : '✗'} ${row.label}`);
  }
  console.log(`\n  preflight ready: ${report.preflight?.ready}`);
  if (!report.ok) {
    console.error('\nEnv checks failed — fix backend/.env before --apply.');
    process.exit(1);
  }

  const intervalHours = (getSweepIntervalMs() / 3_600_000).toFixed(1);
  console.log(`\nScheduler config (when enabled): interval ~${intervalHours}h, limit=${process.env.TRON_SWEEP_SCHEDULER_LIMIT || '500'}`);
  console.log('MASTER_WALLET_TRANSFERS_PAUSED: live sweeps skip until WITHDRAWALS_PAUSED / MASTER_WALLET_TRANSFERS_PAUSED are cleared.');

  if (!opts.apply) {
    console.log('\nDry run — no files changed. Re-run with --apply to enable scheduler + PM2.');
    process.exit(0);
  }

  const envEntries = [['TRON_SWEEP_SCHEDULER_ENABLED', 'true']];
  if (opts.dryRunScheduler) {
    envEntries.push(['TRON_SWEEP_SCHEDULER_DRY_RUN', 'true']);
  }
  upsertEnvLines(ENV_FILE, envEntries);
  for (const [k, v] of envEntries) {
    process.env[k] = v;
  }
  console.log(`\nUpdated ${ENV_FILE} (${envEntries.map(([k]) => k).join(', ')})`);

  const ecosystemPath = writeEcosystemConfig();
  console.log(`Wrote ${ecosystemPath}`);

  const pm2Version = runPm2(['--version']);
  if (pm2Version.status !== 0) {
    console.error('\npm2 is not installed. Install Node PM2 globally, then re-run --apply.');
    console.error('Scheduler env is enabled; start manually: node server.js');
    process.exit(1);
  }

  const describe = runPm2(['describe', PM2_APP_NAME]);
  let pm2Result;
  if (describe.status === 0) {
    pm2Result = runPm2(['reload', ecosystemPath, '--update-env']);
    console.log(`\npm2 reload ${PM2_APP_NAME} (--update-env)`);
  } else {
    pm2Result = runPm2(['start', ecosystemPath, '--update-env']);
    console.log(`\npm2 start ${PM2_APP_NAME}`);
  }

  if (pm2Result.status !== 0) {
    console.error(pm2Result.stderr || pm2Result.stdout || 'pm2 failed');
    process.exit(pm2Result.status || 1);
  }

  runPm2(['save']);
  console.log('\nDone. In-process sweep scheduler runs inside PM2 (no crontab).');
  console.log('Logs: pm2 logs', PM2_APP_NAME);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
