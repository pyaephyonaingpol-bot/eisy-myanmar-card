#!/usr/bin/env node
'use strict';

/**
 * Write gitignored repo `.env` from Cloud Agent / shell secrets (never prints values).
 * Usage: node backend/scripts/materialize-local-env.js
 */
const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.join(__dirname, '..', '..');
const ENV_PATH = path.join(REPO_ROOT, '.env');
const ENV_LOCAL_PATH = path.join(REPO_ROOT, '.env.local');
const TURSO_LIBSQL =
  'libsql://eisymyanmar-pyaephyonaingpol-bot.aws-ap-northeast-1.turso.io';

function firstEnv(...names) {
  for (const name of names) {
    const v = String(process.env[name] ?? '').trim();
    if (v) return v;
  }
  return '';
}

function dotenvLine(key, value) {
  const v = String(value ?? '');
  if (/[\s#"'\\]/.test(v)) {
    return `${key}="${v.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
  }
  return `${key}=${v}`;
}

const entries = [
  ['NODE_ENV', firstEnv('NODE_ENV') || 'development'],
  ['DATABASE_URL', (() => {
    const u = firstEnv('DATABASE_URL', 'TURSO_DATABASE_URL');
    if (/^libsql:/i.test(u) || /^https?:/i.test(u)) return u;
    return TURSO_LIBSQL;
  })()],
  ['DATABASE_AUTH_TOKEN', firstEnv('DATABASE_AUTH_TOKEN', 'TURSO_AUTH_TOKEN')],
  ['TRON_HD_ENABLED', firstEnv('TRON_HD_ENABLED') || 'true'],
  ['TRON_HD_MNEMONIC', firstEnv('TRON_HD_MNEMONIC')],
  ['TRONGRID_API_KEY', firstEnv('TRONGRID_API_KEY', 'TRON_API_KEY', 'TRON_PRO_API_KEY')],
  ['TRON_FULL_HOST', firstEnv('TRON_FULL_HOST', 'TRONGRID_FULL_HOST') || 'https://api.trongrid.io'],
  ['TRON_ENERGY_API_URL', firstEnv('TRON_ENERGY_API_URL')],
  ['TRON_ENERGY_API_KEY', firstEnv('TRON_ENERGY_API_KEY')],
  ['TRON_NETTS_REAL_IP', firstEnv('TRON_NETTS_REAL_IP')],
  ['TRON_SWEEP_NETTS_SETTLE_MS', firstEnv('TRON_SWEEP_NETTS_SETTLE_MS') || '2000'],
  ['TRON_NETTS_FETCH_TIMEOUT_MS', firstEnv('TRON_NETTS_FETCH_TIMEOUT_MS') || '25000'],
  ['MASTER_PRIVATE_KEY', firstEnv('MASTER_PRIVATE_KEY', 'MASTER_WALLET_PRIVATE_KEY', 'TRON_MASTER_PRIVATE_KEY')],
  ['MASTER_WALLET_ADDRESS', firstEnv('MASTER_WALLET_ADDRESS', 'TRON_MASTER_WALLET')],
  ['ADMIN_API_KEY', firstEnv('ADMIN_API_KEY')],
];

const required = ['DATABASE_AUTH_TOKEN', 'TRON_HD_MNEMONIC', 'TRONGRID_API_KEY'];
const missing = required.filter((k) => !firstEnv(
  ...(k === 'TRONGRID_API_KEY' ? ['TRONGRID_API_KEY', 'TRON_API_KEY', 'TRON_PRO_API_KEY'] : [k]),
));

const lines = [
  '# Generated by backend/scripts/materialize-local-env.js — gitignored; do not commit.',
  `# ${new Date().toISOString()}`,
  '',
  ...entries.filter(([, v]) => String(v).trim() !== '').map(([k, v]) => dotenvLine(k, v)),
  '',
];

const body = lines.join('\n');
fs.writeFileSync(ENV_PATH, body, { mode: 0o600 });
// `.env.local` overrides Cloud Agent shell (e.g. wrong postgresql DATABASE_URL).
fs.writeFileSync(ENV_LOCAL_PATH, body, { mode: 0o600 });
const n = entries.filter(([, v]) => String(v).trim()).length;
console.log(`[materialize-local-env] Wrote ${ENV_PATH} and ${ENV_LOCAL_PATH} (${n} keys each)`);

if (missing.length) {
  console.error('[materialize-local-env] Still MISSING in Cloud Agent / shell:', missing.join(', '));
  console.error('Add the same names/values as Vercel → Project → Environment Variables, then re-run this agent or script.');
  process.exit(1);
}

process.exit(0);
