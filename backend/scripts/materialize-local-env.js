#!/usr/bin/env node
'use strict';

/**
 * Write gitignored repo `.env` from Cloud Agent / shell secrets (never prints values).
 * Uses Vercel-first variable names (TRON_API_KEY, DATABASE_URL, …).
 * Usage: node backend/scripts/materialize-local-env.js
 */
const fs = require('fs');
const path = require('path');

const {
  firstEnv,
  databaseUrl,
  databaseAuthToken,
  tronApiKey,
  tronFullHost,
  normalizePlatformEnvAliases,
} = require('../src/lib/envAliases');

// Prefer Cloud Agent / shell secrets — do not load stale .env.local from disk first.
normalizePlatformEnvAliases();

const REPO_ROOT = path.join(__dirname, '..', '..');
const BACKEND_DIR = path.join(__dirname, '..');
const ENV_PATH = path.join(REPO_ROOT, '.env');
const ENV_LOCAL_PATH = path.join(REPO_ROOT, '.env.local');
/** Primary local override path for backend dev + smoke scripts (see loadEnv.js). */
const BACKEND_ENV_LOCAL_PATH = path.join(BACKEND_DIR, '.env.local');
const TURSO_LIBSQL =
  'libsql://eisymyanmar-pyaephyonaingpol-bot.aws-ap-northeast-1.turso.io';

async function verifyTursoConnection(url, authToken) {
  if (!url || !authToken) return { ok: false, reason: 'missing_url_or_token' };
  try {
    const { createClient } = require('@libsql/client');
    const client = createClient({ url, authToken });
    await client.execute('SELECT 1 AS ok');
    return { ok: true };
  } catch (err) {
    return { ok: false, reason: err.message || String(err) };
  }
}

function dotenvLine(key, value) {
  const v = String(value ?? '');
  if (/[\s#"'\\]/.test(v)) {
    return `${key}="${v.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
  }
  return `${key}=${v}`;
}

function resolvedDatabaseUrl() {
  const u = databaseUrl();
  if (/^libsql:/i.test(u) || /^https?:/i.test(u)) return u;
  return TURSO_LIBSQL;
}

/** Vercel-first names written to .env */
const entries = [
  ['NODE_ENV', firstEnv('NODE_ENV') || 'development'],
  ['DATABASE_URL', resolvedDatabaseUrl()],
  ['DATABASE_AUTH_TOKEN', databaseAuthToken()],
  ['TRON_HD_ENABLED', firstEnv('TRON_HD_ENABLED') || 'true'],
  ['TRON_HD_MNEMONIC', firstEnv('TRON_HD_MNEMONIC')],
  ['TRON_API_KEY', tronApiKey()],
  ['TRON_FULL_HOST', tronFullHost()],
  ['TRON_ENERGY_API_URL', firstEnv('TRON_ENERGY_API_URL')],
  ['TRON_ENERGY_API_KEY', firstEnv('TRON_ENERGY_API_KEY')],
  ['TRON_NETTS_REAL_IP', firstEnv('TRON_NETTS_REAL_IP')],
  ['TRON_SWEEP_NETTS_SETTLE_MS', firstEnv('TRON_SWEEP_NETTS_SETTLE_MS') || '2000'],
  ['TRON_NETTS_FETCH_TIMEOUT_MS', firstEnv('TRON_NETTS_FETCH_TIMEOUT_MS') || '25000'],
  ['MASTER_PRIVATE_KEY', firstEnv('MASTER_PRIVATE_KEY', 'MASTER_WALLET_PRIVATE_KEY', 'TRON_MASTER_PRIVATE_KEY')],
  ['MASTER_WALLET_ADDRESS', firstEnv('MASTER_WALLET_ADDRESS', 'TRON_MASTER_WALLET')],
  ['ADMIN_API_KEY', firstEnv('ADMIN_API_KEY')],
];

async function main() {
const missing = [];
if (!databaseAuthToken()) missing.push('DATABASE_AUTH_TOKEN (or TURSO_AUTH_TOKEN / LIBSQL_AUTH_TOKEN)');
if (!firstEnv('TRON_HD_MNEMONIC')) missing.push('TRON_HD_MNEMONIC');
if (!tronApiKey()) missing.push('TRON_API_KEY (or TRONGRID_API_KEY / TRON_PRO_API_KEY)');

const lines = [
  '# Generated by backend/scripts/materialize-local-env.js — gitignored; do not commit.',
  `# ${new Date().toISOString()}`,
  '',
  ...entries.filter(([, v]) => String(v).trim() !== '').map(([k, v]) => dotenvLine(k, v)),
  '',
];

const body = lines.join('\n');
const targets = [ENV_PATH, ENV_LOCAL_PATH, BACKEND_ENV_LOCAL_PATH];
for (const filePath of targets) {
  fs.writeFileSync(filePath, body, { mode: 0o600 });
}
const n = entries.filter(([, v]) => String(v).trim()).length;
console.log(
  `[materialize-local-env] Wrote ${targets.length} files (${n} keys):`,
  targets.map((p) => path.relative(REPO_ROOT, p)).join(', '),
);

const tursoUrl = resolvedDatabaseUrl();
const tursoToken = databaseAuthToken();
const tursoCheck = await verifyTursoConnection(tursoUrl, tursoToken);
if (tursoCheck.ok) {
  console.log('[materialize-local-env] Turso connectivity: OK');
} else {
  console.error('[materialize-local-env] Turso connectivity FAILED — DATABASE_AUTH_TOKEN in this VM is not accepted.');
  console.error('[materialize-local-env] Use the Cursor environment prompt to add secrets copied from Vercel (Production), then start a new agent run and re-run this script.');
  if (!missing.includes('DATABASE_AUTH_TOKEN (or TURSO_AUTH_TOKEN / LIBSQL_AUTH_TOKEN)')) {
    missing.push('valid DATABASE_AUTH_TOKEN for Turso (current token rejected)');
  }
}

if (missing.length) {
  console.error('[materialize-local-env] Still MISSING or invalid:');
  for (const m of missing) console.error(`  - ${m}`);
  process.exit(1);
}

process.exit(0);
}

main().catch((err) => {
  console.error('[materialize-local-env] Fatal:', err.message || err);
  process.exit(1);
});
