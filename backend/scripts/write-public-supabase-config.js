#!/usr/bin/env node
'use strict';

/**
 * Write a browser-readable public Supabase config snippet.
 * Used at Vercel build time so Google OAuth does not depend solely on
 * /api/config/supabase cold-start availability.
 *
 * Run: node backend/scripts/write-public-supabase-config.js
 */
const fs = require('fs');
const path = require('path');

require('../src/lib/loadEnv');
const { getPublicSupabaseConfig } = require('../src/lib/supabase');

const cfg = getPublicSupabaseConfig();
const payload = cfg.enabled
  ? { enabled: true, url: cfg.url, anonKey: cfg.anonKey, reason: 'ok' }
  : { enabled: false, url: null, anonKey: null, reason: cfg.reason || 'missing_credentials' };

const body = [
  '/* Generated by backend/scripts/write-public-supabase-config.js — do not edit */',
  `window.__EISY_SUPABASE_PUBLIC__ = ${JSON.stringify(payload)};`,
  '',
].join('\n');

const targets = [
  path.join(__dirname, '../public/supabase-public-config.js'),
  path.join(__dirname, '../../public/supabase-public-config.js'),
];

for (const target of targets) {
  try {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, body, 'utf8');
    console.log('[supabase-public-config] wrote', target, 'enabled=', payload.enabled);
  } catch (err) {
    console.warn('[supabase-public-config] skip', target, err.message);
  }
}
